package config

import (
	"reflect"
	"strings"
)

// ModulesMarkdown returns the module reference, docs/modules.md: the keys
// of every module that isn't hidden, with their types, defaults and docs.
func ModulesMarkdown(modules []Module, docs Docs) []byte {
	var b strings.Builder
	b.WriteString(`<!-- Code generated by go generate (internal/gen); DO NOT EDIT. -->
<!-- Edit the doc comments of the module config structs instead. -->

# Modules

maisys's built-in modules, and the keys you can set for each one. Each module is a table in profile and machine files, named after the module. Modules are off until a file turns them on with ` + "`enabled = true`" + `. The exception is [sudo](#sudo), which has no ` + "`enabled`" + ` key: its ` + "`nopasswd`" + ` key turns it on.

A machine's config is built in layers: each module's defaults (listed below), then each profile in the order the machine file lists them, then the machine file itself. The layers are merged like this:

- **Single values:** the last layer that sets a value wins.
- **Tables,** including tables keyed by name such as ` + "`files.items`" + `: merged key by key, so a later layer only needs the keys it changes. A new entry in a table keyed by name starts from the defaults listed for its keys.
- **Lists that are "combined across layers":** each layer adds its items to the list, leaving out duplicates and keeping the order. A later layer can't remove an item.
- **Other lists:** replaced by the later layer.

Keys are case-sensitive. maisys ignores keys it doesn't know, so a config written for a newer maisys still works, but ` + "`maisys config validate`" + ` reports each one as an error, which catches typos. Editors that support JSON schemas for TOML can complete and check keys with ` + "`config.schema.json`" + `, which is published with each release: point to it with a ` + "`#:schema`" + ` line at the top of the file.

`)

	b.WriteString("## Machine and profile files\n\n")
	b.WriteString("Besides the module tables, these keys go at the top of machine and profile files.\n\n")
	b.WriteString("| Key | Type | Description |\n|---|---|---|\n")
	for _, k := range fileKeys() {
		b.WriteString("| " + codeSpan(k.key) + " | " + typeName(k.typ) + " | " + markdownText(k.doc) + " |\n")
	}

	b.WriteString("\n## Contents\n\n| Module | What it does | Works on |\n|---|---|---|\n")
	for _, mod := range modules {
		info := mod.Info()
		if info.Hidden {
			continue
		}
		b.WriteString("| [" + markdownText(info.Name) + "](#" + info.Name + ") | " + markdownText(info.Summary) + " | " + worksOn(info) + " |\n")
	}

	for _, mod := range modules {
		info := mod.Info()
		if info.Hidden {
			continue
		}
		b.WriteString("\n## " + markdownText(info.Name) + "\n\n")
		b.WriteString(markdownText(info.Summary) + "\n\n")
		b.WriteString("Works on " + worksOn(info) + ".\n\n")
		b.WriteString("| Key | Type | Default | Description |\n|---|---|---|---|\n")
		cfg := reflect.Indirect(reflect.ValueOf(mod.NewConfig()))
		for _, r := range docRows(cfg, tomlKey(info.Name), docs) {
			b.WriteString("| " + codeSpan(r.key) + " | " + r.typ + " | " + r.def + " | " + markdownText(r.doc) + " |\n")
		}
	}
	return []byte(b.String())
}

// worksOn describes the systems a module works on, such as "Fedora and
// Ubuntu, amd64 only".
func worksOn(info ModuleInfo) string {
	s := osNames(info.OS)
	if len(info.Arch) > 0 {
		archs := make([]string, len(info.Arch))
		for i, a := range info.Arch {
			archs[i] = string(a)
		}
		s += ", " + joinAnd(archs) + " only"
	}
	return s
}

// docRow is a row of a module's table of keys.
type docRow struct {
	key, typ, def, doc string
}

// docRows returns the rows for the keys of v, a config struct, whose table
// is at prefix. Entries of tables keyed by name are listed with <name> in
// their path.
func docRows(v reflect.Value, prefix string, docs Docs) []docRow {
	var rows []docRow
	for _, k := range configKeys(v) {
		key := prefix + "." + tomlKey(k.name)
		row := docRow{key: key, typ: typeName(k.value.Type()), doc: k.doc(docs)}
		switch k.value.Kind() {
		case reflect.Struct:
			rows = append(rows, row)
			rows = append(rows, docRows(k.value, key, docs)...)
		case reflect.Map:
			rows = append(rows, row)
			if elem := k.value.Type().Elem(); elem.Kind() == reflect.Struct {
				rows = append(rows, docRows(newEntry(elem), key+".<name>", docs)...)
			}
		default:
			row.def = codeSpan(tomlValue(k.value))
			rows = append(rows, row)
		}
	}
	return rows
}

// typeName describes a config type, such as "list of strings".
func typeName(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Struct:
		return "table"
	case reflect.Map:
		return "table of " + plural(t.Elem())
	case reflect.Slice, reflect.Array:
		return "list of " + plural(t.Elem())
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "integer"
	case reflect.Float32, reflect.Float64:
		return "number"
	default:
		return "string"
	}
}

func plural(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Struct, reflect.Map:
		return "tables"
	case reflect.Slice, reflect.Array:
		return "lists"
	default:
		return typeName(t) + "s"
	}
}

// codeSpan writes s as Markdown code, in a table cell.
func codeSpan(s string) string {
	fence := "`"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	if strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		s = " " + s + " "
	}
	return fence + strings.ReplaceAll(s, "|", `\|`) + fence
}

// markdownText escapes text for a Markdown table cell, leaving the code
// spans in it (between backticks) as they are.
func markdownText(text string) string {
	parts := strings.Split(text, "`")
	if len(parts)%2 == 0 {
		// An unmatched backtick: escape it too.
		return strings.ReplaceAll(markdownEscaper.Replace(text), "`", "\\`")
	}
	for i, p := range parts {
		if i%2 == 0 {
			parts[i] = markdownEscaper.Replace(p)
		} else {
			parts[i] = strings.ReplaceAll(p, "|", `\|`)
		}
	}
	return strings.Join(parts, "`")
}

var markdownEscaper = strings.NewReplacer(
	`\`, `\\`,
	`|`, `\|`,
	`*`, `\*`,
	`~`, `\~`,
	`<`, `\<`,
	`[`, `\[`,
	`]`, `\]`,
)

// osNames describes a list of operating systems, such as "Fedora and
// Ubuntu".
func osNames(list []OS) string {
	names := make([]string, len(list))
	for i, o := range list {
		switch o {
		case Fedora:
			names[i] = "Fedora"
		case Ubuntu:
			names[i] = "Ubuntu"
		case Windows:
			names[i] = "Windows"
		default:
			names[i] = string(o)
		}
	}
	return joinAnd(names)
}

// joinAnd joins items as in "a, b and c".
func joinAnd(items []string) string {
	if len(items) < 2 {
		return strings.Join(items, "")
	}
	return strings.Join(items[:len(items)-1], ", ") + " and " + items[len(items)-1]
}
