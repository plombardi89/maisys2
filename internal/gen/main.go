// Command gen generates the files that come from the module config structs
// and their doc comments:
//
//   - internal/modules/docs_gen.go, which holds the doc comments, since
//     they aren't available at run time;
//   - docs/modules.md, the module reference;
//   - schema/config.schema.json, the JSON schema for config files.
//
// go generate runs it in internal/modules.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"

	"github.com/plombardi89/maisys2/internal/config"
	"github.com/plombardi89/maisys2/internal/modules"
)

// schemaURL is where releases publish the schema.
const schemaURL = "https://github.com/plombardi89/maisys2/releases/latest/download/config.schema.json"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	files, err := generate(root)
	if err != nil {
		return err
	}
	for _, name := range slices.Sorted(maps.Keys(files)) {
		file := filepath.Join(root, filepath.FromSlash(name))
		if old, err := os.ReadFile(file); err == nil && bytes.Equal(old, files[name]) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(file, files[name], 0o644); err != nil {
			return err
		}
	}
	return nil
}

// repoRoot returns the directory holding go.mod, starting from the current
// directory.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("can't find go.mod")
		}
		dir = parent
	}
}

// generate returns the generated files, keyed by their slash-separated
// paths from the repo root.
func generate(root string) (map[string][]byte, error) {
	all := modules.All()
	docs, err := moduleDocs(root, all)
	if err != nil {
		return nil, err
	}
	source, err := docsSource(docs)
	if err != nil {
		return nil, err
	}
	schema, err := config.Schema(all, docs, schemaURL)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"internal/modules/docs_gen.go": source,
		"docs/modules.md":              config.ModulesMarkdown(all, docs),
		"schema/config.schema.json":    schema,
	}, nil
}

// docsSource returns the source of docs_gen.go, whose Docs function returns
// docs.
func docsSource(docs config.Docs) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by go run ../gen; DO NOT EDIT.

package modules

import "github.com/plombardi89/maisys2/internal/config"

// Docs returns the doc comments of the modules' config types and their
// fields, which describe each key for users.
func Docs() config.Docs {
	return config.Docs{
`)
	for _, key := range slices.Sorted(maps.Keys(docs)) {
		fmt.Fprintf(&b, "%s: %s,\n", strconv.Quote(key), strconv.Quote(docs[key]))
	}
	b.WriteString("}\n}\n")
	return format.Source(b.Bytes())
}
